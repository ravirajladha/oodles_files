<h6>How do I get started with Janant?</h6>
<p>Janant is a network centric B2B platform, designed specifically for small &
medium businesses in India. It brings traders, wholesalers, retailers and
manufacturers in India on to a single platform. With real insights into active
trends, and great B2B features, Janant brings to them the power of
technology to scale & nurture their business. To get started with Janant, you
need to download Janant App, and register your business. Once registered,
you will have access to all the trades and selections from sellers from all
over India.</p>
<h6>Where can I download Janant App?</h6>
<p>You can download Janant App by visiting www.Janant.online on your mobile.
How do I register? Are there specific requirements to register on Janant?
You can register with your mobile number and OTP. Once you have put the
mobile number and OTP, registration process will start. Being a B2B
platform, the only requirement to register with Janant is that you own or work
at a business or a shop. Given the trade oriented nature of the
transactions, end consumers will not find enough value on Janant.</p>
<h6>How do I buy / trade on Janant?</h6>
<p>You can buy / sell / trade on Janant using Janant App. If you are a new buyer
you can discover selection in following ways:
 Go to 'Search' tab search for your product requirements. We have
tried our best to create a set of pre-defined searches that can quickly
get you to a wide variety of products available on Janant.
 In the same tab, you can also search for products,categories,vendors
(such as manufacturers, wholesalers, distributers).
You can simply click the 'Buy Now' button to buy the shown product. Once
you have pressed the Buy button, you need to select the quantity of
available variants or sets of the product. The product will be added to your
cart.</p>
<h6>I am unable to add products to cart. It says MOQ / Minimum Quantity not met? What is
MOQ / Minimum Quantity?</h6>
<p>MOQ is Minimum Order Quantity. MOQ is set by sellers and can be
different for different products / listings. A buyer needs to purchase at least
the mentioned MOQ to continue the trade.
Why am I getting MOV not met? What is MOV?
MOV stands for Minimum Order Value. MOV applies at a single order per
seller basis. Sellers put MOV to ensure a minimum business per order per
buyer.</p>
<h5>Payments:<h5> <h6>How do I pay for the purchase?</h6>
<p>You can pay as prepaid or by cash once the order is delivered to you.
There is provision to purchase the products on credit but it is available on
few sellers. Please reach out to Janant Support to check if you can avail
credit for your purchase(s).
How do I get the purchased products? Who provides the courier services?
As a buyer, you need not worry about arranging courier services to pickup
and deliver your order. Our own Logistics arranges for the order to be
picked up.</p>
<h6>Who pays for the courier?</h6>
<p>As a buyer, you are liable to pay for the courier services. Please check the
Review Order Page to get an estimate of the logistics charges. You can
also refer to the rate card to understand cost to courier goods between
different parts of India.
When do I need to pay for the courier?
Courier charges are required to be paid along with the payment for the
order to the seller. You can check the shipping / logistics charges on the
order page.</p>
<h6>How long does it take for the courier to deliver products?</h6>
<p>It depends on where the seller is shipping from and what is the buyer's
location. Usually, interstate deliveries take anywhere between 7-10 days
while within the state can happen within a week. Please check with Janant
Support to understand how long will it take to get your order.</p>
<h6>Where can I see the orders I have placed?</h6>
<p>You can see all your orders in 'My Orders' screen.
Can I track my delivery? How do I track the progress in order processing?
You can track the status of your order from My Orders page. Click on any
order to see it's details.</p>
